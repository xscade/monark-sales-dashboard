import { randomUUID } from "node:crypto";
import {
  GOOGLE_HASH_OPTIONS,
  META_HASH_OPTIONS,
  computeAttributionExpiry,
  decideResolution,
  hashEmail,
  hashPhone,
  normalizeIdentity,
  scoreSpam,
  splitName,
  type IdentifierMatch,
} from "@monark/core";
